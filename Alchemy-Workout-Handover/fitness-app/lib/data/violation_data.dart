/// 累計違規次數（`[BE-13]`，2026-09-25）。
///
/// ## 為什麼要獨立一個 collection
///
/// 階梯累犯制的級距由累計違規次數決定，所以這個數字**必須是當事人
/// 自己改不動的**。而既有的兩個候選位置都不行：
///
///   · `public_profiles/{uid}` —— 規則是「本人可寫」，他自己就能清掉
///   · `users/{uid}/…` —— 規則是「本人全權讀寫」，同上
///
/// 所以另開一份：**管理員可寫、當事人唯讀**。當事人要讀得到，
/// 因為處罰畫面要告訴他這是第幾次。
///
/// 在此之前這個數字只活在 `AppState._violations` 這個本機 Map 裡 ——
/// 管理員判了別人違規三次，對方那邊完全不知道，而且重開 App 就歸零。
abstract class ViolationSource {
  /// 某人的累計違規次數。讀不到（沒有紀錄）回 0。
  ///
  /// 當事人讀自己的，或管理員讀別人的。其餘一律被規則拒絕。
  Future<int> countOf(String uid);

  /// 記一次違規，回傳記完之後的次數。**只有管理員叫得動。**
  ///
  /// [name] 只是給管理端看的，判定不靠它。
  Future<int> increment(String uid, {required String name});

  /// 退回一次違規（申訴成立）。回傳退完之後的次數，**不會低於 0**。
  ///
  /// 規格：申訴成立時「該次違規視為不成立」—— 所以是退一次，
  /// 不是歸零。他之前可能還有別的違規。
  Future<int> decrement(String uid);
}
